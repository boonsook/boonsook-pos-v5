CREATE TABLE public.sales (
  id bigint PRIMARY KEY,
  order_no text UNIQUE,
  customer_id bigint REFERENCES public.customers(id),
  customer_name text,
  total_amount numeric(12,2), subtotal numeric(12,2), discount_amount numeric(12,2),
  paid_amount numeric(12,2), change_amount numeric(12,2), credit_used_amount numeric(14,2),
  vat_amount numeric(15,2), vat_rate numeric(5,2), is_credit boolean DEFAULT false,
  stock_reverted_at timestamptz, note text
