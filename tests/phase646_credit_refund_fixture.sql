CREATE TABLE public.warehouse_stock (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES public.products(id),
  warehouse_id integer NOT NULL REFERENCES public.warehouses(id),
  stock integer NOT NULL DEFAULT 0 CHECK(stock>=0), min_stock integer DEFAULT 0,
  UNIQUE(product_id,warehouse_id)
);
CREATE FUNCTION public.sync_product_stock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE public.products SET stock=(SELECT coalesce(sum(stock),0) FROM public.warehouse_stock WHERE product_id=NEW.product_id)
  WHERE id=NEW.product_id;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_sync_product_stock AFTER INSERT OR UPDATE ON public.warehouse_stock
  FOR EACH ROW EXECUTE FUNCTION public.sync_product_stock();
