  WHERE source_table IS NOT NULL AND source_id IS NOT NULL;
CREATE FUNCTION public.check_period_not_locked() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RETURN NEW; END $$;
CREATE TRIGGER trg_check_period_locked BEFORE INSERT OR UPDATE OR DELETE ON public.journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.check_period_not_locked();
CREATE TABLE public.journal_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id bigint NOT NULL REFERENCES public.journal_entries(id) ON DELETE CASCADE,
  line_no integer, account_code text REFERENCES public.chart_of_accounts(code),
  debit numeric(14,2) DEFAULT 0, credit numeric(14,2) DEFAULT 0, description text,
  CHECK(debit>=0 AND credit>=0)
);
CREATE FUNCTION public.enforce_je_lines_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id bigint;
BEGIN
  v_id := coalesce(NEW.entry_id,OLD.entry_id);
  IF EXISTS (SELECT 1 FROM public.journal_entries e WHERE e.id=v_id AND
    (e.total_debit IS DISTINCT FROM (SELECT coalesce(sum(debit),0) FROM public.journal_lines WHERE entry_id=v_id)
     OR e.total_credit IS DISTINCT FROM (SELECT coalesce(sum(credit),0) FROM public.journal_lines WHERE entry_id=v_id))) THEN
    RAISE EXCEPTION 'unbalanced journal lines';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_je_lines_balance AFTER INSERT OR UPDATE OR DELETE ON public.journal_lines
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.enforce_je_lines_balance();
