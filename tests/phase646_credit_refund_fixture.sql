CREATE TABLE public.warehouses (id integer PRIMARY KEY);
CREATE TABLE public.product_bundles (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  bundle_id bigint NOT NULL, child_product_id bigint NOT NULL, qty numeric NOT NULL
